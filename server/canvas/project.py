"""One project, one ``.agora/`` directory: canvases, comment threads, sessions and the
workspace manifest stored next to the code they describe. Format: web/docs/project-storage.md.

Every write is atomic (temp file in the same directory + ``os.replace``) and versioned:
a file's version is a short sha256 of its bytes. Writers pass the version they last saw
(``base``); if the file changed in between (another tab, an editor, ``git checkout``) the
write is refused with ``Conflict`` instead of silently overwriting. ``force`` skips the
check (the user chose "keep mine"). Session logs are append-only JSONL under the same
compare-and-swap rule.

The store knows files, not the UI: it formats canvases as Excalidraw scenes, folds
session logs, and otherwise treats payloads as opaque JSON.
"""

